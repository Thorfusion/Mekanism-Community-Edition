package mekanism.nuclear.common.config;

import io.netty.buffer.ByteBuf;
import java.io.File;
import mekanism.common.content.boiler.BoilerCoolantSimulation;
import net.minecraftforge.common.config.Configuration;

/** Server-authoritative stable fission reactor values. */
public final class NuclearFissionConfig
{
    private static final String CATEGORY = "fission_reactor";

    public static final double AMBIENT_TEMPERATURE = 300D;
    public static final double BOIL_TEMPERATURE = 373.15D;
    public static final double MIN_DAMAGE_TEMPERATURE = 1_200D;
    public static final double MAX_DAMAGE_TEMPERATURE = 1_800D;
    public static final double MAX_DAMAGE = 100D;

    private static long energyPerFissionFuel;
    private static double casingHeatCapacity;
    private static double surfaceAreaTarget;
    private static double defaultBurnRate;
    private static long burnPerAssembly;
    private static long maxFuelPerAssembly;
    private static int cooledCoolantPerVolume;
    private static long heatedCoolantPerVolume;
    private static int boilerHeatedCoolantPerTank;
    private static int boilerCooledCoolantPerTank;
    private static double excessWasteRatio;
    private static boolean meltdownsEnabled;
    private static float meltdownRadius;
    private static double meltdownChance;
    private static double meltdownRadiationMultiplier;
    private static double postMeltdownDamage;

    static
    {
        resetDefaults();
    }

    private NuclearFissionConfig()
    {
    }

    public static synchronized void load(File file)
    {
        Configuration config = new Configuration(file);
        config.load();
        load(config);
        if (config.hasChanged())
        {
            config.save();
        }
    }

    public static synchronized void load(Configuration config)
    {
        energyPerFissionFuel = positiveLong(config, "EnergyPerFissionFuel",
              1_000_000L, "Heat energy generated by each mB of Fissile Fuel.");
        casingHeatCapacity = config.get(CATEGORY, "CasingHeatCapacity", 1_000D,
              "Heat capacity contributed by each exterior reactor block.",
              1, 1_000_000).getDouble();
        surfaceAreaTarget = config.get(CATEGORY, "SurfaceAreaTarget", 4D,
              "Average exposed fuel-assembly surface area required for full boil efficiency.",
              1, Double.MAX_VALUE).getDouble();
        defaultBurnRate = config.get(CATEGORY, "DefaultBurnRate", 0.1D,
              "Default configured Fissile Fuel burn rate in mB/t.",
              0.001D, 1D).getDouble();
        burnPerAssembly = positiveLong(config, "BurnPerAssembly", 1L,
              "Maximum burn rate in mB/t contributed by each fuel assembly block.");
        maxFuelPerAssembly = positiveLong(config, "MaxFuelPerAssembly", 8_000L,
              "Fuel and waste capacity in mB contributed by each fuel assembly block.");
        cooledCoolantPerVolume = config.getInt("CooledCoolantPerVolume", CATEGORY,
              100_000, 1, Integer.MAX_VALUE / (18 * 18 * 18),
              "Cooled coolant capacity per reactor block.");
        heatedCoolantPerVolume = positiveLong(config, "HeatedCoolantPerVolume",
              1_000_000L, "Heated coolant capacity per reactor block.");
        boilerHeatedCoolantPerTank = config.getInt(
              "BoilerHeatedCoolantPerTank", CATEGORY, 256_000, 1,
              Integer.MAX_VALUE,
              "Heated coolant capacity per lower Boiler tank block in mB.");
        boilerCooledCoolantPerTank = config.getInt(
              "BoilerCooledCoolantPerTank", CATEGORY, 256_000, 1,
              Integer.MAX_VALUE,
              "Cooled coolant capacity per upper Boiler tank block in mB.");
        applyBoilerConfiguration();
        excessWasteRatio = config.get(CATEGORY, "ExcessWasteRatio", 0.9D,
              "Waste fill ratio at which a Logic Adapter emits a critical-waste signal.",
              0, 1).getDouble();
        meltdownsEnabled = config.getBoolean("MeltdownsEnabled", CATEGORY, true,
              "Whether critically damaged Fission Reactors can explode and release radiation.");
        meltdownRadius = (float)config.get(CATEGORY, "MeltdownRadius", 8D,
              "Explosion radius for a Fission Reactor meltdown.", 1, 500).getDouble();
        meltdownChance = config.get(CATEGORY, "MeltdownChance", 0.001D,
              "Per-tick meltdown chance at 100% damage; scales with excess damage.",
              0, 1).getDouble();
        meltdownRadiationMultiplier = config.get(CATEGORY,
              "MeltdownRadiationMultiplier", 50D,
              "Multiplier applied to radioactive contents released by a meltdown.",
              0.1D, 1_000_000D).getDouble();
        postMeltdownDamage = config.get(CATEGORY, "PostMeltdownDamage", 75D,
              "Damage retained after a meltdown.", 0, MAX_DAMAGE).getDouble();
    }

    private static long positiveLong(Configuration config, String key,
          long fallback, String comment)
    {
        return NuclearConfigValues.getLong(config, CATEGORY, key, fallback, 1,
              comment);
    }

    public static long getEnergyPerFissionFuel()
    {
        return energyPerFissionFuel;
    }

    public static double getCasingHeatCapacity()
    {
        return casingHeatCapacity;
    }

    public static double getSurfaceAreaTarget()
    {
        return surfaceAreaTarget;
    }

    public static double getDefaultBurnRate()
    {
        return defaultBurnRate;
    }

    public static long getBurnPerAssembly()
    {
        return burnPerAssembly;
    }

    public static long getMaxFuelPerAssembly()
    {
        return maxFuelPerAssembly;
    }

    public static int getCooledCoolantPerVolume()
    {
        return cooledCoolantPerVolume;
    }

    public static long getHeatedCoolantPerVolume()
    {
        return heatedCoolantPerVolume;
    }

    public static double getExcessWasteRatio()
    {
        return excessWasteRatio;
    }

    public static boolean isMeltdownsEnabled()
    {
        return meltdownsEnabled;
    }

    public static float getMeltdownRadius()
    {
        return meltdownRadius;
    }

    public static double getMeltdownChance()
    {
        return meltdownChance;
    }

    public static double getMeltdownRadiationMultiplier()
    {
        return meltdownRadiationMultiplier;
    }

    public static double getPostMeltdownDamage()
    {
        return postMeltdownDamage;
    }

    public static void write(ByteBuf data)
    {
        data.writeLong(energyPerFissionFuel);
        data.writeDouble(casingHeatCapacity);
        data.writeDouble(surfaceAreaTarget);
        data.writeDouble(defaultBurnRate);
        data.writeLong(burnPerAssembly);
        data.writeLong(maxFuelPerAssembly);
        data.writeInt(cooledCoolantPerVolume);
        data.writeLong(heatedCoolantPerVolume);
        data.writeInt(boilerHeatedCoolantPerTank);
        data.writeInt(boilerCooledCoolantPerTank);
        data.writeDouble(excessWasteRatio);
        data.writeBoolean(meltdownsEnabled);
        data.writeFloat(meltdownRadius);
        data.writeDouble(meltdownChance);
        data.writeDouble(meltdownRadiationMultiplier);
        data.writeDouble(postMeltdownDamage);
    }

    public static void read(ByteBuf data)
    {
        energyPerFissionFuel = atLeast(data.readLong(), 1L);
        casingHeatCapacity = clamp(data.readDouble(), 1D, 1_000_000D);
        surfaceAreaTarget = atLeast(data.readDouble(), 1D);
        defaultBurnRate = clamp(data.readDouble(), 0.001D, 1D);
        burnPerAssembly = atLeast(data.readLong(), 1L);
        maxFuelPerAssembly = atLeast(data.readLong(), 1L);
        cooledCoolantPerVolume = clamp(data.readInt(), 1,
              Integer.MAX_VALUE / (18 * 18 * 18));
        heatedCoolantPerVolume = atLeast(data.readLong(), 1L);
        boilerHeatedCoolantPerTank = Math.max(data.readInt(), 1);
        boilerCooledCoolantPerTank = Math.max(data.readInt(), 1);
        applyBoilerConfiguration();
        excessWasteRatio = clamp(data.readDouble(), 0D, 1D);
        meltdownsEnabled = data.readBoolean();
        meltdownRadius = (float)clamp(data.readFloat(), 1D, 500D);
        meltdownChance = clamp(data.readDouble(), 0D, 1D);
        meltdownRadiationMultiplier = clamp(data.readDouble(), 0.1D,
              1_000_000D);
        postMeltdownDamage = clamp(data.readDouble(), 0D, MAX_DAMAGE);
    }

    static void resetDefaults()
    {
        energyPerFissionFuel = 1_000_000L;
        casingHeatCapacity = 1_000D;
        surfaceAreaTarget = 4D;
        defaultBurnRate = 0.1D;
        burnPerAssembly = 1L;
        maxFuelPerAssembly = 8_000L;
        cooledCoolantPerVolume = 100_000;
        heatedCoolantPerVolume = 1_000_000L;
        boilerHeatedCoolantPerTank = 256_000;
        boilerCooledCoolantPerTank = 256_000;
        applyBoilerConfiguration();
        excessWasteRatio = 0.9D;
        meltdownsEnabled = true;
        meltdownRadius = 8F;
        meltdownChance = 0.001D;
        meltdownRadiationMultiplier = 50D;
        postMeltdownDamage = 75D;
    }

    private static long atLeast(long value, long minimum)
    {
        return Math.max(minimum, value);
    }

    private static void applyBoilerConfiguration()
    {
        BoilerCoolantSimulation.configureTankCapacities(
              boilerHeatedCoolantPerTank, boilerCooledCoolantPerTank);
    }

    private static double atLeast(double value, double minimum)
    {
        return Double.isNaN(value) ? minimum : Math.max(minimum, value);
    }

    private static int clamp(int value, int minimum, int maximum)
    {
        return Math.max(minimum, Math.min(maximum, value));
    }

    private static double clamp(double value, double minimum, double maximum)
    {
        return Double.isNaN(value) ? minimum
              : Math.max(minimum, Math.min(maximum, value));
    }
}
